#!/usr/bin/env python3
"""Generate ios/Keyboard/EmojiCatalog+Data.swift from vendor/UnicodeEmoji/emoji-test.txt."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "vendor/UnicodeEmoji/emoji-test.txt"
TARGET = ROOT / "ios/Keyboard/EmojiCatalog+Data.swift"

# The native keyboard's order. Its first page holds both smileys and people; components are not shown on their own.
GROUPS = {
    "Smileys & Emotion": "smileysAndPeople",
    "People & Body": "smileysAndPeople",
    "Animals & Nature": "animalsAndNature",
    "Food & Drink": "foodAndDrink",
    "Activities": "activity",
    "Travel & Places": "travelAndPlaces",
    "Objects": "objects",
    "Symbols": "symbols",
    "Flags": "flags",
}
ORDER = list(dict.fromkeys(GROUPS.values()))
# Skin tones are variants of an emoji the native keyboard shows once.
MODIFIERS = re.compile("[\U0001F3FB-\U0001F3FF]")

line_pattern = re.compile(r"^([0-9A-F ]+?)\s*; fully-qualified\s*# \S+ E(\d+\.\d+) ")
emoji = {key: [] for key in ORDER}
group = None
for line in SOURCE.read_text(encoding="utf-8").splitlines():
    if line.startswith("# group: "):
        group = GROUPS.get(line[len("# group: "):].strip())
        continue
    match = line_pattern.match(line)
    if not match or group is None:
        continue
    value = "".join(chr(int(code, 16)) for code in match.group(1).split())
    if MODIFIERS.search(value):
        continue
    emoji[group].append((value, float(match.group(2))))

def literal(values):
    return '"' + "".join(values) + '"'

# iOS 26.0 shows Emoji 16.0, iOS 26.4 Emoji 17.0. Newer ones are kept in their place and dropped where the
# system cannot draw them. A newer list needs its own iOS version in EmojiCatalog first.
SUPPORTED = 16.0
GATED = 17.0
# The file's own version counts, since its additions might all be filtered out above.
source_version = float(re.search(r"^# Version: (\d+\.\d+)", SOURCE.read_text(encoding="utf-8"), re.M).group(1))
if source_version > GATED:
    raise SystemExit(f"Emoji {source_version} has no iOS version yet. Map it in EmojiCatalog.isDrawable and here.")
lines = [
    "// Generated by scripts/generate_emoji.py from vendor/UnicodeEmoji/emoji-test.txt. Do not edit.",
    "",
    "extension EmojiCatalog.Category {",
    "    /// Every emoji of the category in Unicode's order, one `Character` each.",
    "    var allEmoji: String {",
    "        switch self {",
]
lines += ["        case .recent:", '            ""']
for key in ORDER:
    lines.append(f"        case .{key}:")
    lines.append(f"            {literal(value for value, _ in emoji[key])}")
lines += [
    "        }",
    "    }",
    "",
    f"    /// Emoji newer than Emoji {SUPPORTED}, which iOS 26.0 cannot draw yet.",
    "    static let newerEmoji: Set<Character> = [",
]
for key in ORDER:
    for value, version in emoji[key]:
        if version > SUPPORTED:
            lines.append(f'        "{value}",')
lines += ["    ]", "}", ""]
TARGET.write_text("\n".join(lines), encoding="utf-8")
